"""
Synthetic Dataset Generator for StayNearby Demonstration.

DISCLAIMER & DOCUMENTATION:
- All datasets generated by this module are purely simulated/synthetic demonstration data.
- They are designed to demonstrate the machine learning lifecycle, feature engineering,
  ranking pipelines, MLOps tracking, and model evaluation locally.
- They do NOT represent real-world customer behavior or actual rental booking demand in Chennai.
- Any relationships modeled here (e.g., higher weekend demand or distance penalty) are
  artificially injected heuristics for demonstration purposes only.
"""

from typing import Tuple, List, Dict
import numpy as np
import pandas as pd
from datetime import datetime, timedelta

CHENNAI_AREAS = [
    "Guindy", "Velachery", "Adyar", "T. Nagar", 
    "Anna Nagar", "Mylapore", "OMR (Thoraipakkam)", "Nungambakkam"
]

PROPERTY_TYPES = [
    "workspace_studio", "private_room", "guest_suite", "entire_apartment", "day_cabin"
]

AMENITIES_POOL = [
    "wifi", "air_conditioning", "work_desk", "power_backup", 
    "private_restroom", "coffee_tea", "parking", "quiet_zone"
]

TIME_SLOTS = ["morning", "afternoon", "evening", "night"]

def generate_synthetic_recommender_dataset(
    num_sessions: int = 400,
    candidates_per_session: int = 15,
    random_seed: int = 42
) -> pd.DataFrame:
    """
    Generates synthetic interaction sessions for training the recommendation ranker.
    
    Simulated rules:
    - Distance penalty: Closer candidate properties receive higher interaction probability.
    - Budget fit: Properties priced within user's budget receive higher relevance.
    - Amenity match: Greater overlap with requested amenities increases relevance.
    - Rating bonus: Higher rated properties receive positive boost.
    - Simulated noise added to simulate stochastic user decisions.
    """
    np.random.seed(random_seed)
    records = []

    for s_idx in range(num_sessions):
        session_id = f"sess_{s_idx:04d}"
        user_id = (s_idx % 50) + 1  # 50 simulated unique users
        budget = float(np.random.choice([250.0, 350.0, 500.0, 750.0, 1000.0, 1500.0]))
        preferred_type = np.random.choice(PROPERTY_TYPES)
        req_amenities_count = np.random.randint(2, 5)
        user_req_amenities = set(np.random.choice(AMENITIES_POOL, size=req_amenities_count, replace=False))
        
        # User requested duration: hourly (1-4 hrs), half-day (~6 hrs), full-day (~24 hrs)
        duration_hours = float(np.random.choice([2.0, 4.0, 6.0, 8.0, 24.0]))

        for c_idx in range(candidates_per_session):
            prop_id = 100 + c_idx + (s_idx % 20)
            distance_km = round(float(np.random.exponential(scale=4.5) + 0.3), 2)
            distance_km = min(distance_km, 35.0)

            prop_type = np.random.choice(PROPERTY_TYPES)
            type_match = 1.0 if prop_type == preferred_type else 0.0

            # Price per hour
            price = round(float(np.random.uniform(150.0, 1200.0)), 2)
            total_cost = round(price * max(1.0, duration_hours / 2.0), 2)
            price_ratio = min(2.5, total_cost / max(1.0, budget))

            # Amenities
            prop_amenities_count = np.random.randint(3, 7)
            prop_amenities = set(np.random.choice(AMENITIES_POOL, size=prop_amenities_count, replace=False))
            amenity_overlap = len(user_req_amenities.intersection(prop_amenities))
            amenity_match_ratio = round(amenity_overlap / len(user_req_amenities), 2)

            rating = round(float(np.clip(np.random.normal(4.3, 0.4), 2.5, 5.0)), 1)
            review_count = int(np.random.randint(2, 60))

            # Calculate simulated latent relevance score
            # Heuristic simulation: 
            # - distance penalty
            # - budget affinity
            # - amenity affinity
            # - rating bonus
            latent_utility = (
                - 0.08 * distance_km
                - 1.2 * max(0.0, price_ratio - 1.0)
                + 1.8 * amenity_match_ratio
                + 0.6 * type_match
                + 0.5 * (rating - 3.5)
                + np.random.normal(0, 0.4)
            )

            # Map latent score into discrete relevance label:
            # 0: Not relevant / skipped
            # 1: Clicked / viewed
            # 2: Favourited
            # 3: Booked
            if latent_utility > 1.8:
                relevance_label = 3
            elif latent_utility > 0.8:
                relevance_label = 2
            elif latent_utility > -0.2:
                relevance_label = 1
            else:
                relevance_label = 0

            records.append({
                "session_id": session_id,
                "user_id": user_id,
                "property_id": prop_id,
                "distance_km": distance_km,
                "price": price,
                "budget": budget,
                "price_ratio": price_ratio,
                "duration_hours": duration_hours,
                "amenity_match_ratio": amenity_match_ratio,
                "type_match": type_match,
                "rating": rating,
                "review_count": review_count,
                "relevance_label": relevance_label,
                "is_synthetic": True,
            })

    df = pd.DataFrame(records)
    return df

def generate_synthetic_demand_dataset(
    start_date: str = "2026-08-01",
    num_days: int = 90,
    random_seed: int = 42
) -> pd.DataFrame:
    """
    Generates synthetic neighbourhood demand time-series data.
    
    Simulated trends:
    - IT corridor areas (OMR, Guindy, Velachery) have higher weekday daytime and evening demand.
    - Commercial/shopping hubs (T. Nagar, Anna Nagar) have high weekend demand.
    - Time-of-day variations (afternoon and evening peaks).
    - Random fluctuations and noise.
    """
    np.random.seed(random_seed)
    base_date = datetime.strptime(start_date, "%Y-%m-%d")
    records = []

    # Area baseline multipliers
    area_weights = {
        "Guindy": 1.2,
        "Velachery": 1.1,
        "Adyar": 1.0,
        "T. Nagar": 1.3,
        "Anna Nagar": 1.15,
        "Mylapore": 0.9,
        "OMR (Thoraipakkam)": 1.25,
        "Nungambakkam": 1.05,
    }

    slot_weights = {
        "morning": 0.8,
        "afternoon": 1.2,
        "evening": 1.4,
        "night": 0.5,
    }

    for d in range(num_days):
        current_dt = base_date + timedelta(days=d)
        date_str = current_dt.strftime("%Y-%m-%d")
        day_of_week = current_dt.weekday()  # 0=Monday, 6=Sunday
        is_weekend = 1 if day_of_week in [5, 6] else 0
        month = current_dt.month

        for area in CHENNAI_AREAS:
            base_area = area_weights.get(area, 1.0)
            avg_price = round(float(np.random.normal(450.0, 50.0)), 2)
            available_listings = int(np.random.randint(12, 35))

            for slot in TIME_SLOTS:
                slot_w = slot_weights.get(slot, 1.0)
                
                # Heuristic weekend boost for retail/residential areas, weekday for IT
                weekend_mod = 1.3 if (is_weekend and area in ["T. Nagar", "Anna Nagar", "Adyar"]) else 1.0
                it_mod = 1.25 if (not is_weekend and area in ["OMR (Thoraipakkam)", "Guindy"]) else 1.0

                mean_requests = 10.0 * base_area * slot_w * weekend_mod * it_mod
                noise = np.random.normal(0, 2.0)
                actual_requests = max(0, int(round(mean_requests + noise)))
                
                # Simulated historical moving average
                hist_requests = max(0, int(round(mean_requests * np.random.uniform(0.9, 1.1))))
                occupancy_rate = round(min(1.0, actual_requests / max(1, available_listings)), 2)

                records.append({
                    "neighbourhood": area,
                    "date": date_str,
                    "day_of_week": day_of_week,
                    "is_weekend": is_weekend,
                    "month": month,
                    "time_slot": slot,
                    "available_listings": available_listings,
                    "avg_price": avg_price,
                    "historical_requests": hist_requests,
                    "occupancy_rate": occupancy_rate,
                    "actual_requests": actual_requests,
                    "is_synthetic": True,
                })

    df = pd.DataFrame(records)
    return df
